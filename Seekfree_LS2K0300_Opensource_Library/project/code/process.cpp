/********************************************************************************************************************
 * 上下板通信处理
 ********************************************************************************************************************/
#include "zf_common_headfile.h"

//-------------------------------------------------------------------------------------------------------------------
// 函数简介     接收上板指令并控制电机
// 使用示例     transport();  // 放在主循环 while(1) 中轮询
// 备注信息     通过 UART1 (/dev/ttyS1) 接收上板发送的指令
//              "01" -> 所有电机 PWM 3000 (前进)
//              "02" -> 所有电机 PWM 6000 (前进)
//              "03" -> 所有电机 PWM -4000 (后退)
//-------------------------------------------------------------------------------------------------------------------
void transport(void)
{
    uint8_t buf[4];

    // 先检查是否有数据可读，避免无效调用
    if (!uart1_available())
        return;

    int n = uart1_recv(buf, sizeof(buf));
    if (n <= 0)
        return;

    // 根据接收到的指令设置所有电机 PWM
    if (n == 2 && buf[0] == '0' && buf[1] == '1')
    {
        Motor_Move_Straight(3000);          // 指令 01: 所有电机 PWM 3000
    }
    else if (n == 2 && buf[0] == '0' && buf[1] == '2')
    {
        Motor_Move_Straight(6000);          // 指令 02: 所有电机 PWM 6000
    }
    else if (n == 2 && buf[0] == '0' && buf[1] == '3')
    {
        Motor_Move_Straight(-4000);         // 指令 03: 所有电机 PWM -4000 (反转)
    }
}
